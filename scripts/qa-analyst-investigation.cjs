// Browser acceptance of the approved investigation controls, using local data.
const { chromium } = require(process.argv[2] || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { load } = require('./analyst-ts-loader.cjs');
const { normalizeDay } = load('lib/analyst/data.ts');
const { nextObservation, observationSecond } = load('lib/analyst/timeline-navigation.ts');
const base = process.argv[3] || 'http://localhost:3001/qoe/';
const output = 'outputs/analyst-ui/browser-2026-10-26';
fs.mkdirSync(output, { recursive: true });
const dataset = JSON.parse(fs.readFileSync('public/mdt-data.json', 'utf8'));
const rich = dataset.customers.reduce((best, c) => (c.gnssSampleCount || 0) > (best?.gnssSampleCount || 0) ? c : best, null);
const entry = dataset.days.find((d) => d.customerId === rich.id);
const day = JSON.parse(fs.readFileSync(path.join('public', entry.dataPath), 'utf8'));
const normalized = normalizeDay(dataset, day, 'MDT');
(async () => {
  let browser;
  const errors = [];
  try {
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(base + '?source=MDT', { waitUntil: 'domcontentloaded', timeout: 90000 });
    const summary = page.getByLabel('전체 분석 요약');
    await summary.waitFor({ timeout: 60000 });
    const totals = await summary.innerText();
    assert(totals.includes('25,548') && totals.includes('23,085'));
    const rank = page.getByLabel('조사할 구역 순위');
    const first = rank.getByRole('button').first();
    const alias = await first.innerText();
    assert(!alias.includes('grid60:'));
    assert(alias.startsWith('조사구역'));
    await first.click();
    await page.waitForFunction(() => new URL(location.href).searchParams.has('cell'));
    const selectedArea = new URL(page.url()).searchParams.get('cell');
    assert((await page.getByLabel('현재 조사 조건').innerText()).includes(alias));
    await page.waitForFunction(() => Array.from(document.querySelectorAll('.leaflet-tile')).some((image) => image.getAttribute('src')?.includes('/Base/16/')), { timeout: 30000 });
    const hourly = page.getByLabel('시간대별 저품질 통화');
    await hourly.getByRole('button', { name: '비율', exact: true }).click();
    const unavailable = hourly.getByRole('button', { name: /^0시 저품질/ });
    assert((await unavailable.innerText()).includes('—'));
    assert((await unavailable.getAttribute('title')).includes('통화 없음'));
    await hourly.getByRole('button', { name: /^16시 저품질/ }).click();
    assert.equal(new URL(page.url()).searchParams.get('cell'), selectedArea);
    assert((await page.getByLabel('현재 조사 조건').innerText()).includes('16시'));
    assert.equal(await summary.innerText(), totals);
    await page.getByRole('button', { name: '목록 확장', exact: true }).click();
    const tableHeight = await page.getByLabel('조사 통화 목록').locator('table').evaluate((table) => table.parentElement.clientHeight);
    assert(tableHeight > 240, 'Expanded investigation list has usable height');
    await page.getByRole('button', { name: '지도 중심', exact: true }).click();
    await page.screenshot({ path: output + '/overview-1920.png', fullPage: true });
    await page.getByLabel('조사 통화 목록').getByRole('button', { name: /통화 분석$/ }).first().click();
    await page.getByLabel('선택 통화 무선 시간축').waitFor({ timeout: 30000 });
    await page.getByRole('button', { name: '품질 현황으로 돌아가기', exact: true }).click();
    await summary.waitFor();
    assert.equal(new URL(page.url()).searchParams.get('cell'), selectedArea);
    assert.equal(new URL(page.url()).searchParams.get('hour'), '16');
    await page.getByRole('button', { name: '조사 조건 전체 해제', exact: true }).click();
    assert.equal(new URL(page.url()).searchParams.get('cell'), null);
    assert.equal(new URL(page.url()).searchParams.get('hour'), null);
    await page.setViewportSize({ width: 1366, height: 768 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    await page.screenshot({ path: output + '/overview-1366.png', fullPage: true });

    await page.goto(base + `?source=MDT&customer=${rich.id}&date=${entry.date}`, { waitUntil: 'domcontentloaded' });
    await page.getByLabel('선택 통화 무선 시간축').waitFor({ timeout: 30000 });
    const selectedCall = new URL(page.url()).searchParams.get('call');
    const samples = normalized.samples.filter((s) => s.callId === selectedCall).sort((a,b) => observationSecond(a)-observationSecond(b)||a.index-b.index);
    const slider = page.getByRole('slider', { name: '관측 시점 선택' });
    await slider.press('Home');
    await page.getByLabel('시간축 표시 범위').selectOption('60');
    assert.equal(await slider.getAttribute('max'), String(samples.length - 1));
    const beforeIndex = Number(new URL(page.url()).searchParams.get('sample'));
    const expected = nextObservation(samples, beforeIndex, 'condition');
    const condition = page.getByRole('button', { name: '다음 조건 관측', exact: true });
    if (expected !== null) {
      await condition.click();
      await page.waitForFunction((index) => Number(new URL(location.href).searchParams.get('sample')) === index, expected);
    } else assert.equal(await condition.isDisabled(), true);
    await slider.press('End');
    await page.waitForFunction((index) => Number(new URL(location.href).searchParams.get('sample')) === index, samples.at(-1).index);
    assert.equal(await page.getByRole('button', { name: '다음 관측', exact: true }).isDisabled(), true);
    await slider.press('Home');
    await page.getByRole('button', { name: '전체 시간으로 복원', exact: true }).click();
    await page.getByRole('button', { name: '통화 목록 접기', exact: true }).click();
    await page.getByRole('button', { name: '통화 목록 펼치기', exact: true }).waitFor();
    await page.getByRole('button', { name: '근거 중심', exact: true }).click();
    await page.getByText('위치 근거', { exact: true }).click();
    assert((await page.locator('body').innerText()).includes('EPSG:5179'));
    assert((await page.locator('body').innerText()).includes('정확도 정보 없음'));
    await page.getByLabel('지도 색상 지표').selectOption('sinr');
    assert((await page.getByLabel('지도 색상 수치 기준').innerText()).includes('SINR < 3 dB'));
    await page.getByRole('button', { name: '선택 관측 위치로 지도 이동', exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    await page.screenshot({ path: output + '/contract-1366.png', fullPage: true });
    await page.setViewportSize({ width: 1920, height: 1080 });
    await page.getByRole('button', { name: '균형 보기', exact: true }).click();
    await page.getByRole('button', { name: '통화 목록 펼치기', exact: true }).click();
    await page.screenshot({ path: output + '/contract-1920.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ browserErrors: errors, areaAliases: true, scopePreserved: true, explicitMapFocus: true, hourlyRateAndMissingDenominator: true, expandedList: true, backToInvestigation: true, timelineZoomAndOriginalIndex: true, conditionNavigation: true, layoutControls: true, evidenceGroups: true, numericLegend: true, desktopFits: true }));
  } finally { await browser?.close(); }
})().catch((error) => { console.error(error.stack); process.exitCode = 1; });
