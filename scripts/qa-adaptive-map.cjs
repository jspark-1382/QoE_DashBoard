// Optional browser QA: node scripts/qa-adaptive-map.cjs <path-to-playwright>
const {chromium}=require(process.argv[2]||'playwright');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1920,height:1080}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const consoleErrors=[];page.on('console',message=>{if(message.type()==='error')consoleErrors.push(message.text().replace(/https?:\/\/\S+/g,'[URL]'));});
 await page.goto('http://localhost:3000/qoe/?source=MDT&customer=mdt-site&date=2026-09-04');
 await page.getByRole('button',{name:'고객 위치 추정',exact:true}).waitFor();
 await page.getByRole('button',{name:'고객 위치 추정',exact:true}).click();
 await page.getByLabel('Adaptive 위치 상세').waitFor();
 console.log('INITIAL',await page.getByLabel('Adaptive 위치 상세').innerText());
 await page.locator('summary').filter({hasText:'추정 설정 · Adaptive'}).click();
 await page.getByLabel('추정 방식 필터').selectOption('MULTILATERATION');
 await page.getByRole('button',{name:'다음',exact:true}).click();
 console.log('MULTI',await page.getByLabel('Adaptive 위치 상세').innerText());
 await page.getByLabel('Debug',{exact:true}).check();
 await page.getByLabel('불확실성 반경',{exact:true}).uncheck();
 await page.getByLabel('불확실성 반경',{exact:true}).check();
 await page.locator('summary').filter({hasText:'추정 설정 · Adaptive'}).click();
 await page.getByRole('button',{name:'크게 보기',exact:true}).click();
 await page.getByRole('button',{name:'Zoom in',exact:true}).click();
 await page.waitForTimeout(400);
 await page.getByRole('button',{name:'Zoom out',exact:true}).click();
 await page.waitForTimeout(400);
 const host=page.getByLabel('MDT 기지국 기반 추정 위치 지도');
 const rect=await host.boundingBox();
 await page.mouse.move(rect.x+rect.width*.5,rect.y+rect.height*.5);
 await page.mouse.down();await page.mouse.move(rect.x+rect.width*.5+60,rect.y+rect.height*.5+35,{steps:5});await page.mouse.up();
 await page.locator('.location-station-marker').first().click();
 console.log('STATION',await page.locator('.leaflet-popup-content').innerText());
 await page.locator('.leaflet-popup-close-button').click();
 await page.locator('[aria-label^="추정 UE "]').last().click();
 console.log('UE POPUP',await page.locator('.leaflet-popup-content').innerText());
 await page.locator('.leaflet-popup-close-button').click();
 await page.waitForTimeout(3000);
 console.log('TILES',await page.locator('.leaflet-tile').evaluateAll(images=>({total:images.length,loaded:images.filter(i=>i.complete&&i.naturalWidth>0).length})));
 fs.mkdirSync('outputs',{recursive:true});
 await page.screenshot({path:'outputs/adaptive-map-qa.png'});
 await page.keyboard.press('Escape');
 await page.locator('summary').filter({hasText:'추정 설정 · Adaptive'}).click();
 await page.getByLabel('추정 방식 필터').selectOption('ALL');
 await page.getByLabel('신뢰도 필터').selectOption('A');
 console.log('EMPTY',await page.getByLabel('Adaptive 위치 상세').innerText());
 await page.getByLabel('신뢰도 필터').selectOption('ALL');
 await page.getByLabel('추정 시작 시간').fill('10:20');
 await page.getByLabel('추정 종료 시간').fill('10:30');
 await page.getByRole('button',{name:'다음',exact:true}).click();
 console.log('TIME FILTER',await page.getByLabel('Adaptive 위치 상세').innerText());
 await page.getByRole('button',{name:'재생',exact:true}).click();
 await page.waitForTimeout(1100);
 await page.getByRole('button',{name:'일시정지',exact:true}).click();
 await page.getByLabel('위치추정 알고리즘').selectOption('legacy');
 await page.getByLabel('추정 주파수 형식').waitFor({state:'attached'});
 await page.getByRole('button',{name:'고객 위치 추정',exact:true}).click();
 await page.getByLabel('MDT 또는 실측').selectOption('실측');
 await page.getByRole('heading',{name:'고객체감품질 지도',exact:true}).waitFor();
 await page.waitForTimeout(1000);
 await page.screenshot({path:'outputs/measured-map-regression.png'});
 console.log('ERRORS',JSON.stringify(errors));
 console.log('CONSOLE_ERRORS',JSON.stringify(consoleErrors));
 await browser.close();
 if(errors.length||consoleErrors.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1);});
