const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require(process.argv[2]||'playwright');
const base=(process.argv[3]||'http://127.0.0.1:3019/qoe').replace(/\/$/,'');
const output=process.argv[4]||'outputs/quality-improvement-two-deploy/full-period-qa';
fs.mkdirSync(output,{recursive:true});
const url=base+'/?variant=improvement2&dateStart=2026-10-26&dateEnd=2026-10-30&mapMode=improvement';
const models=[['hdbscan',20,16],['st_dbscan',7,5],['adaptive_kde',18,15],['spatial_scan',20,17],['bayesian',20,20]];
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const p=await browser.newPage({viewport:{width:1440,height:990}});
  const errors=[],tileResponse=[];p.on('pageerror',e=>errors.push(e.message));
  p.on('response',r=>{try{if(new URL(r.url()).hostname==='api.vworld.kr')tileResponse.push(r.status())}catch{}});
  await p.goto(url,{waitUntil:'domcontentloaded'});
  const picker=p.getByRole('region',{name:'후보 분석 목적 선택'});
  const full=picker.getByRole('button',{name:'전체 기간 후보 분석 (기본)'});
  const holdout=picker.getByRole('button',{name:'알고리즘 성능 검증 (기간 분리)'});
  await full.waitFor({timeout:90000});
  assert.equal(await full.getAttribute('aria-pressed'),'true');
  const select=p.getByRole('combobox',{name:'조사 후보 알고리즘'});
  await select.waitFor({timeout:45000});
  const original=p.getByRole('region',{name:'조사 후보 지역 목록'});
  await original.getByRole('button',{name:/후보 지역 8/}).waitFor({timeout:25000});
  assert.equal(await original.getByRole('button').count(),8);
  const zone=p.getByRole('region',{name:'선택 후보 지역 요약'});
  await zone.waitFor();
  assert((await zone.innerText()).includes('미실시'),'all mode must not imply failed validation');
  const fullMap=p.getByLabel('개선 후보 지도').first();
  await fullMap.locator('.leaflet-container').waitFor();
  await p.waitForTimeout(4500);
  let tiles=await fullMap.evaluate(el=>({loaded:[...el.querySelectorAll('img.leaflet-tile')].filter(x=>x.complete&&x.naturalWidth>0).length,warning:el.querySelector('output')?.textContent}));
  assert(tiles.loaded>0&&!tiles.warning,'map background failed: '+JSON.stringify(tiles));
  await p.screenshot({path:output+'/full-default-8.png',fullPage:false});
  await holdout.click();
  assert.equal(await holdout.getAttribute('aria-pressed'),'true');
  await original.getByRole('button',{name:/후보 지역 7/}).waitFor({timeout:40000});
  assert.equal(await original.getByRole('button').count(),7,'holdout original DBSCAN must remain 7');
  assert((await p.getByLabel('조사 후보 핵심 현황').innerText()).includes('새 고객 재관측'));
  const checked=[];
  for(const [id,allCount,evalCount] of models){
   await select.selectOption(id);
   const list=p.getByRole('region',{name:'선택 모델 조사 후보 목록'});
   await list.getByRole('button').first().waitFor({timeout:45000});
   assert.equal(await list.getByRole('button').count(),evalCount,id+' evaluation count');
   const section=p.getByRole('region',{name:/선택 모델 .* 조사 후보/}).first();
   assert((await section.innerText()).includes('후속 평가 기반 성능 검증'));
   await full.click();
   await list.getByRole('button').first().waitFor({timeout:40000});
   assert.equal(await list.getByRole('button').count(),allCount,id+' all count');
   const metrics=p.getByLabel('선택 모델 후보 통계');
   assert((await metrics.innerText()).includes('별도 평가일 없이 전체 기간 사용'));
   const details=p.getByRole('region',{name:'선택 모델 후보 상세 근거'});
   assert((await details.innerText()).includes('미실시'),'all model must not display zero unverified as failed test');
   await list.getByRole('button').nth(1).click();
   assert((await details.innerText()).includes('후보 지역 2'));
   if(id==='hdbscan')await p.screenshot({path:output+'/hdbscan-full.png',fullPage:false});
   await holdout.click();
   await list.getByRole('button').first().waitFor({timeout:40000});
   assert.equal(await list.getByRole('button').count(),evalCount,id+' back to evaluation');
   checked.push({id,all:allCount,evaluation:evalCount});
  }
  await select.selectOption('dbscan');await full.click();
  await original.getByRole('button',{name:/후보 지역 8/}).waitFor({timeout:45000});
  assert.equal(await original.getByRole('button').count(),8);
  await p.getByRole('button',{name:'지도 전체 화면'}).click();
  const popup=p.getByRole('dialog',{name:'개선 2안 조사 후보 지도'});
  await popup.waitFor();
  assert.equal(await popup.getByLabel('전체화면 조사 후보 탐색').locator('button[data-candidate-id]').count(),8);
  await popup.getByRole('button',{name:'알고리즘 설명·시뮬레이션'}).click();
  const guide=p.getByRole('dialog',{name:'DBSCAN · 후보 산정 시뮬레이터'});
  await guide.getByRole('button',{name:'알고리즘 설명'}).click();
  assert((await guide.getByLabel('조사 후보 지도 알고리즘 설명').innerText()).includes('100m'),'Popup explanation should describe true DBSCAN eps');
  await p.keyboard.press('Escape');
  await p.keyboard.press('Escape');
  await p.setViewportSize({width:390,height:810});await p.waitForTimeout(350);
  const width=await p.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
  assert(width.scroll<=width.client+4,'mobile width overflow '+JSON.stringify(width));
  await p.goto(base+'/?variant=improvement2&dateStart=2026-10-30&dateEnd=2026-10-30&mapMode=improvement',{waitUntil:'domcontentloaded'});
  const one=p.getByRole('region',{name:'후보 분석 목적 선택'});
  await one.waitFor({timeout:70000});
  assert(await one.getByRole('button',{name:'알고리즘 성능 검증 (기간 분리)'}).isDisabled());
  assert.equal(await one.getByRole('button',{name:'전체 기간 후보 분석 (기본)'}).getAttribute('aria-pressed'),'true');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({pass:true,baselineAll:8,baselineEval:7,models:checked,tileResponses:tileResponse.length,tileErrors:tileResponse.filter(v=>v!==200).length,mobileNoOverflow:true,oneDayEvaluationDisabled:true,errors}));
 }finally{await browser.close();}
})().catch(e=>{console.error(e.stack||e.message);process.exitCode=1});
