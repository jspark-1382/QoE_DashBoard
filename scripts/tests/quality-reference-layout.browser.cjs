const {chromium}=require(process.argv[2]||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const base=(process.argv[3]||'http://127.0.0.1:3019/qoe').replace(/\/$/,'');
const out=process.argv[4]||'outputs/quality-improvement-two-deploy/reference-qa';
fs.mkdirSync(out,{recursive:true});
const url=base+'/?variant=improvement2&dateStart=2026-10-26&dateEnd=2026-10-30&mapMode=improvement';
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
 const p=await browser.newPage({viewport:{width:1650,height:935}});
 const errors=[],tiles=[];
 p.on('pageerror',e=>errors.push(e.message));
 p.on('response',r=>{try{if(new URL(r.url()).hostname==='api.vworld.kr')tiles.push(r.status())}catch{}});
 await p.goto(url,{waitUntil:'domcontentloaded'});
 const picker=p.getByRole('combobox',{name:'조사 후보 알고리즘'});
 await picker.waitFor({timeout:90000});
 assert.equal(await picker.locator('option').count(),6);
 const main=p.getByLabel('개선 2안 조사 후보 지도');
 await main.getByRole('button',{name:'지도 전체 화면'}).click();
 const dialog=p.getByRole('dialog',{name:'개선 2안 조사 후보 지도'});
 await dialog.waitFor({timeout:15000});
 const toolbar=dialog.getByLabel('전체화면 분석 설정');
 await toolbar.waitFor();
 const fullModel=toolbar.getByRole('combobox',{name:'전체화면 조사 후보 알고리즘'});
 assert.equal(await fullModel.locator('option').count(),6,'fullscreen algorithm menu must remain available');
 const buttons=toolbar.getByRole('button');
 assert(await toolbar.getByRole('button',{name:'전체 기간 후보 분석 (기본)'}).isVisible());
 assert(await toolbar.getByRole('button',{name:'알고리즘 성능 검증 (기간 분리)'}).isVisible());
 const rail=dialog.getByLabel('전체화면 왼쪽 지도 해석 및 알고리즘 설명');
 await rail.waitFor();
 const tabs=rail.getByRole('tablist',{name:'전체화면 알고리즘 정보'});
 assert.equal(await tabs.getByRole('tab').count(),2);
 const card=rail.getByLabel('전체화면 선택 후보 요약');
 const summary=await card.innerText();
 assert(summary.includes('후보 지역 1')&&summary.includes('저MOS 고객')&&summary.includes('표시 반경'),'actual candidate card missing '+summary);
 const actualRadius=(await card.innerText()).match(/표시 반경\s*(\d+)m/);
 assert(actualRadius,'No actual display radius value on card');
 const content=rail.getByLabel('DBSCAN 기반 후보 선정 로직');
 assert((await content.innerText()).includes('100m'));
 const ctas=rail.getByLabel('전체화면 주요 동작');
 assert.equal(await ctas.getByRole('button').count(),2);
 const map=dialog.getByLabel('개선 후보 지도');
 await map.locator('.leaflet-container').waitFor({timeout:15000});
 await p.waitForTimeout(5000);
 const labels=map.locator('.quality-candidate-label');
 assert((await labels.count())>=2,'Expected permanent real candidate labels on map');
 const radiusLabel=map.locator('.quality-candidate-radius-label');
 assert((await radiusLabel.innerText()).includes(actualRadius[1]+'m'),'Radius map label must match calculated candidate');
 const mapTiles=await map.locator('img.leaflet-tile').evaluateAll(list=>list.filter(x=>x.complete&&x.naturalWidth>0).length);
 assert(mapTiles>0,'map tile background missing');
 const dims=await dialog.evaluate(el=>{
   const get=s=>el.querySelector(s);
   const rect=e=>{const r=e.getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom,width:r.width,height:r.height}};
   return {header:rect(get('[aria-label="전체화면 분석 설정"]')),rail:rect(get('[aria-label="전체화면 왼쪽 지도 해석 및 알고리즘 설명"]')),map:rect(get('[aria-label="개선 후보 지도"]')),actions:rect(get('[aria-label="전체화면 주요 동작"]')),card:rect(get('[aria-label="전체화면 선택 후보 요약"]'))};
 });
 assert(dims.header.x>=dims.rail.x&&dims.header.right<=dims.rail.right+2,'Controls must sit inside the left map heading '+JSON.stringify(dims));
 assert(dims.rail.right<=dims.map.x+2,'Left and right overlap '+JSON.stringify(dims));
 assert(dims.rail.width/dims.map.width>.38 && dims.rail.width/dims.map.width<.68,'Reference column ratio mismatch '+JSON.stringify(dims));
 assert(dims.actions.bottom<=dims.rail.bottom+5,'CTA must be inside left rail');
 assert(dims.card.bottom<dims.actions.y,'Card and CTA overlap');
 await p.screenshot({path:out+'/dbscan-1650.png',fullPage:false});
 await ctas.getByRole('button',{name:'시뮬레이터 열기'}).click();
 const dbPopup=p.getByRole('dialog',{name:'DBSCAN · 후보 산정 시뮬레이터'});
 await dbPopup.getByLabel('후보 산정 가상 시뮬레이터').waitFor({timeout:18000});
 await dbPopup.getByRole('button',{name:'시뮬레이터 팝업 닫기'}).click();
 await ctas.getByRole('button',{name:'후보 통화 보기'}).click();
 assert(!(await dialog.isVisible()));
 assert.equal(await p.getByRole('tab',{name:'고객·통화'}).getAttribute('aria-selected'),'true');
 // Map pan and zoom are still interactive.
 await main.getByRole('button',{name:'지도 전체 화면'}).click();
 const dialogAgain=p.getByRole('dialog',{name:'개선 2안 조사 후보 지도'});
 const activeMap=dialogAgain.getByLabel('개선 후보 지도');
 const before=await activeMap.locator('.leaflet-map-pane').evaluate(x=>x.style.transform);
 const b=await activeMap.locator('.leaflet-container').boundingBox();
 await p.mouse.move(b.x+b.width*.56,b.y+b.height*.54);await p.mouse.down();
 await p.mouse.move(b.x+b.width*.56-105,b.y+b.height*.54+85,{steps:8});await p.mouse.up();
 await p.waitForTimeout(850);
 const after=await activeMap.locator('.leaflet-map-pane').evaluate(x=>x.style.transform);
 assert.notEqual(after,before,'pan blocked by fullscreen UI');
 await p.keyboard.press('Escape');
 // Alternative algorithm has matching reference structure.
 await picker.selectOption('hdbscan');
 const alt=p.getByRole('region',{name:'선택 모델 HDBSCAN 조사 후보'});
 await alt.waitFor({timeout:25000});
 await alt.getByRole('button',{name:'지도 전체 화면'}).click();
 const altDialog=p.getByRole('dialog',{name:'대안 모델 조사 후보 지도'});
 await altDialog.waitFor();
 const altRail=altDialog.getByLabel('전체화면 왼쪽 지도 해석 및 모델 시뮬레이션');
 assert.equal(await altRail.getByRole('tablist',{name:'전체화면 알고리즘 정보'}).getByRole('tab').count(),2);
 assert((await altRail.getByLabel('전체화면 선택 후보 요약').innerText()).includes('후보 지역 1'));
 assert((await altRail.getByLabel('선택 알고리즘의 핵심 선정 로직').innerText()).includes('HDBSCAN'));
 await altRail.getByRole('button',{name:'시뮬레이터 열기'}).click();
 const altSimulator=p.getByRole('dialog',{name:'HDBSCAN · 후보 산정 시뮬레이터'});
 await altSimulator.getByLabel('hdbscan 상세 가상 시뮬레이터').waitFor();
 await altSimulator.getByRole('button',{name:'시뮬레이터 팝업 닫기'}).click();
 await altRail.getByRole('tab',{name:'알고리즘 설명'}).click();
 await p.waitForTimeout(1500);
 await p.screenshot({path:out+'/hdbscan-1650.png',fullPage:false});
 const mobile=[];
 for(const w of [1024,800,680,390]){
   await p.setViewportSize({width:w,height:880});await p.waitForTimeout(450);
   const d=await altDialog.evaluate(el=>{
     const r=e=>{const q=e.getBoundingClientRect();return {left:q.left,right:q.right,top:q.top,bottom:q.bottom,width:q.width,height:q.height}};
     return {toolbar:r(el.querySelector('[aria-label="전체화면 분석 설정"]')),rail:r(el.querySelector('[aria-label="전체화면 왼쪽 지도 해석 및 모델 시뮬레이션"]')),map:r(el.querySelector('[aria-label="개선 후보 지도"]')),panel:r(el.querySelector('[class*="railContent"]')),scroll:document.documentElement.scrollWidth,viewport:document.documentElement.clientWidth};
   });
   assert(d,'Missing layout at '+w);
   assert(d.scroll<=d.viewport+4,'Overflow at '+w+': '+JSON.stringify(d));
   assert(d.rail.right<=d.map.left+4 || d.rail.bottom<=d.map.top+4,'Overlap at '+w+': '+JSON.stringify(d));
   assert(d.map.height>=140&&d.panel.height>=55,'Content clipped at '+w+': '+JSON.stringify(d));
   mobile.push({w,mapHeight:Math.round(d.map.height),explanationHeight:Math.round(d.panel.height)});
   if(w===390)await p.screenshot({path:out+'/hdbscan-390.png',fullPage:false});
 }
 // Switching models from the fullscreen top bar must preserve fullscreen mode.
 const modelInside=altDialog.getByRole('combobox',{name:'전체화면 조사 후보 알고리즘'});
 await modelInside.selectOption('spatial_scan');
 await p.waitForFunction(()=>{
   const modal=document.querySelector('[role="dialog"][aria-label="대안 모델 조사 후보 지도"]');
   return modal?.querySelector('[aria-label="선택 알고리즘의 핵심 선정 로직"]')?.textContent?.includes('Spatial Scan');
 },null,{timeout:40000});
 assert(await p.getByRole('dialog',{name:'대안 모델 조사 후보 지도'}).isVisible(),'Fullscreen must remain open after selecting Spatial Scan');
 await p.getByRole('dialog',{name:'대안 모델 조사 후보 지도'}).getByRole('combobox',{name:'전체화면 조사 후보 알고리즘'}).selectOption('dbscan');
 await p.getByRole('dialog',{name:'개선 2안 조사 후보 지도'}).waitFor({timeout:45000});
 assert(await p.getByRole('dialog',{name:'개선 2안 조사 후보 지도'}).isVisible(),'Fullscreen must survive switch back to DBSCAN');
 await p.keyboard.press('Escape');
 assert(tiles.some(x=>x===200)&&!tiles.some(x=>x!==200),'VWorld tile HTTP error '+JSON.stringify([...new Set(tiles)]));
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({pass:true,fullCard:summary,actualRadiusM:parseInt(actualRadius[1],10),mapTiles,fullscreenTools:6,threeTabs:true,twoActions:true,pan:true,mobile,pageErrors:errors}));
 }finally{await browser.close()}
})().catch(e=>{console.error(e.stack||e.message);process.exitCode=1});
