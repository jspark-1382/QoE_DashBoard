const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require(process.argv[2]||'playwright');
const root=(process.argv[3]||'http://127.0.0.1:3019/qoe').replace(/\/$/,'');
const output=process.argv[4]||'outputs/quality-improvement-two-deploy/unified-ui-qa';
fs.mkdirSync(output,{recursive:true});
const url=root+'/?variant=improvement2&dateStart=2026-10-26&dateEnd=2026-10-30&mapMode=improvement';
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const p=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[],tiles=[];
  p.on('pageerror',e=>errors.push(e.message));
  p.on('response',r=>{try{if(new URL(r.url()).hostname==='api.vworld.kr')tiles.push(r.status())}catch{}});
  await p.goto(url,{waitUntil:'domcontentloaded'});
  const toolbar=p.getByLabel('개선 2안 분석 설정');
  await toolbar.waitFor({timeout:90000});
  const model=p.getByRole('combobox',{name:'조사 후보 알고리즘'});
  assert.equal(await model.locator('option').count(),6,'6 algorithm choices must be kept');
  const mode=p.getByRole('region',{name:'후보 분석 목적 선택'});
  assert.equal(await mode.getByRole('button',{name:'전체 기간 후보 분석 (기본)'}).getAttribute('aria-pressed'),'true');
  const header=p.getByRole('region',{name:'개선 2안 분석 안내'});
  const headHeight=await header.evaluate(el=>el.getBoundingClientRect().height);
  assert(headHeight<85,'Top blue hero is still too tall: '+headHeight);
  const list=p.getByRole('region',{name:'조사 후보 지역 목록'});
  await list.getByRole('button',{name:/후보 지역 8/}).waitFor({timeout:30000});
  assert.equal(await list.getByRole('button').count(),8);
  const region=p.getByRole('region',{name:'선택 후보 지역 요약'});
  await region.waitFor();
  const summary=await region.innerText();
  assert(summary.includes('미실시'));
  const customer=p.getByLabel('선택 후보 고객 통화 근거');
  await customer.waitFor();
  const tabs=p.getByRole('tablist',{name:'후보 상세 정보 선택'});
  assert.equal(await tabs.getByRole('tab').count(),3);
  assert.equal(await tabs.getByRole('tab',{name:'선정 요약'}).getAttribute('aria-selected'),'true');
  await tabs.getByRole('tab',{name:'고객·통화'}).click();
  assert(await customer.isVisible());
  await tabs.getByRole('tab',{name:'위치·무선 근거'}).click();
  const rf=p.getByRole('region',{name:'선택 후보 위치 및 무선 근거'});
  await rf.waitFor();
  assert((await rf.innerText()).includes('RF 중앙값'));
  await tabs.getByRole('tab',{name:'선정 요약'}).click();
  await region.waitFor();
  const frame=p.getByLabel('개선 후보 지도').first();
  await frame.locator('.leaflet-container').waitFor({timeout:20000});
  await p.waitForTimeout(3000);
  const loaded=await frame.locator('img.leaflet-tile').evaluateAll(els=>els.filter(x=>x.complete&&x.naturalWidth>0).length);
  assert(loaded>0,'DBSCAN tile background missing');
  await p.screenshot({path:output+'/dbscan-1440.png'});
  const shortcut=p.getByRole('button',{name:'알고리즘 설명·시뮬레이션'});
  await shortcut.click();
  const dlg=p.getByRole('dialog',{name:'DBSCAN · 후보 산정 시뮬레이터'});
  await dlg.getByLabel('후보 산정 가상 시뮬레이터').waitFor({timeout:15000});
  await p.keyboard.press('Escape');
  assert(!(await dlg.isVisible()));
  await model.selectOption('hdbscan');
  const alt=p.getByRole('region',{name:'선택 모델 HDBSCAN 조사 후보'});
  await alt.waitFor({timeout:20000});
  const altList=p.getByRole('region',{name:'선택 모델 조사 후보 목록'});
  await altList.getByRole('button').first().waitFor({timeout:30000});
  assert.equal(await altList.getByRole('button').count(),20);
  const tab2=p.getByRole('tablist',{name:'모델 후보 상세 정보 선택'});
  assert.equal(await tab2.getByRole('tab').count(),3);
  await tab2.getByRole('tab',{name:'고객·통화'}).click();
  const observed=alt.getByLabel('선택 모델 후보의 실제 원본 통화');
  await observed.waitFor();
  await tab2.getByRole('tab',{name:'위치·무선 근거'}).click();
  const altRF=alt.getByRole('region',{name:'대안 모델 위치 및 무선 근거'});
  await altRF.waitFor();
  assert((await altRF.innerText()).includes('GNSS'));
  await tab2.getByRole('tab',{name:'선정 요약'}).click();
  assert(await alt.getByLabel('선택 모델 후보 통계').isVisible());
  await p.screenshot({path:output+'/hdbscan-1440.png'});
  await shortcut.click();
  const dlgAlt=p.getByRole('dialog',{name:'HDBSCAN · 후보 산정 시뮬레이터'});
  await dlgAlt.getByLabel('hdbscan 상세 가상 시뮬레이터').waitFor({timeout:16000});
  await p.keyboard.press('Escape');
  assert(!(await dlgAlt.isVisible()));
  await model.selectOption('spatial_scan');
  const scan=p.getByRole('region',{name:'선택 모델 Spatial Scan 조사 후보'});
  await scan.waitFor();
  assert((await scan.innerText()).includes('탐색 전용'));
  const check=mode.getByRole('button',{name:'알고리즘 성능 검증 (기간 분리)'});
  await check.click();
  await scan.getByRole('region',{name:'선택 모델 조사 후보 목록'}).getByRole('button').first().waitFor();
  assert.equal(await scan.getByRole('region',{name:'선택 모델 조사 후보 목록'}).getByRole('button').count(),17);
  await mode.getByRole('button',{name:'전체 기간 후보 분석 (기본)'}).click();
  await scan.getByRole('region',{name:'선택 모델 조사 후보 목록'}).getByRole('button').first().waitFor();
  assert.equal(await scan.getByRole('region',{name:'선택 모델 조사 후보 목록'}).getByRole('button').count(),20);
  // Layout: map, right panel and new compact toolbar must not overlap.
  await model.selectOption('hdbscan');
  await altList.getByRole('button').first().waitFor();
  const layouts=[];
  for(const w of [1440,1280,1024,800,680,390]){
   await p.setViewportSize({width:w,height:900});await p.waitForTimeout(350);
   const dims=await p.evaluate(()=>{
    const box=el=>{let r=el.getBoundingClientRect();return {x:r.x,right:r.right,y:r.y,bottom:r.bottom,width:r.width,height:r.height}};
    const toolbar=document.querySelector('[aria-label="개선 2안 분석 설정"]');
    const map=document.querySelector('[aria-label="대안 모델 조사 후보 지도"]');
    const side=document.querySelector('[aria-label="모델별 후보 및 선정 근거"]');
    const list=side?.querySelector('[aria-label="선택 모델 조사 후보 목록"] [class*="rows"]');
    if(!toolbar||!map||!side||!list)return null;
    return {scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth,toolbar:box(toolbar),map:box(map),side:box(side),listHeight:box(list).height,listScroll:list.scrollHeight};
   });
   assert(dims,'Missing sections at '+w);
   assert(dims.scroll<=dims.client+4,'Horizontal page overflow '+w+': '+JSON.stringify(dims));
   assert(dims.toolbar.right<=dims.client+3,'Toolbar overflow '+w);
   assert(dims.map.right+5<=dims.side.x || dims.map.bottom+5<=dims.side.y,'Map/right overlap '+w+': '+JSON.stringify(dims));
   assert(dims.listHeight<=235,'Right candidate list pushes detail too far down '+w+': '+JSON.stringify(dims));
   layouts.push({width:w,listHeight:Math.round(dims.listHeight),orientation:dims.map.right<=dims.side.x?'side':'stack'});
   if(w===390)await p.screenshot({path:output+'/hdbscan-390.png'});
  }
  assert(tiles.some(x=>x===200),'Map tiles should successfully load');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({pass:true,models:6,dbscanCandidates:8,hdbscanCandidates:20,modeSwitchScan:[20,17],tabs:true,shortcut:true,tileLoaded:loaded,layouts,errors}));
 }finally{await browser.close()}
})().catch(e=>{console.error(e.stack||e.message);process.exitCode=1});
