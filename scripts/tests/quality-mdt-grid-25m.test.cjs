const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const {load}=require('../analyst-ts-loader.cjs');
const {isValidMdt25mGrid,inVisibleCandidate25m,grid25mCorners,grid25mRsrpColor,selectMdtGridMetric,MDT_GRID_MODES,MDT_RSRP_LEGEND}=load('lib/analyst/mdt-25m-grid.ts');
const grid=JSON.parse(fs.readFileSync(path.join(root,'public/quality-improvement/mdt-grid-25m-v1.json'),'utf8'));
const first=grid.records.find(x=>x.pot==='38415_77716');
test('MDT grid uses original dated 25m POT centers and real per-frequency RSRP',()=>{
 assert(isValidMdt25mGrid(grid));
 assert.equal(grid.referenceOnly,true);
 assert.equal(grid.sourceDate,'2026-11-03');
 assert.equal(grid.gridCells,9226);
 assert.equal(grid.sourceRows,28118);
 assert.equal(grid.measurements,5520908);
 assert(first);
 assert.equal(first.x,960387.5);
 assert.equal(first.y,1942912.5);
 assert.equal(first.lat,37.4846039169);
 assert.equal(first.lon,127.0519376514);
 assert.equal(first.samples,297+8113+527+1107);
 assert.equal(first.rsrp,-90.77);
 assert.deepEqual(first.bands['900'],[-87.1,527]);
 assert.deepEqual(first.bands['1.8광'],[-90.46,8113]);
 assert.deepEqual(first.bands['1.8협'],[-93.43,1107]);
 assert.deepEqual(first.bands['2.1'],[-95.92,297]);
 assert.equal(grid.records.length,new Set(grid.records.map(x=>x.pot)).size);
 assert(grid.records.every(x=>x.samples>0&&x.rsrp>-150&&x.rsrp<0));
});
test('25m grid squares follow UTMK projected grid directions without inventing coordinates',()=>{
 const corners=grid25mCorners(first,grid.basisPerMeter,grid.cellSizeM);
 assert.equal(corners.length,4);
 const meanLat=corners.reduce((sum,p)=>sum+p[0],0)/4;
 const meanLon=corners.reduce((sum,p)=>sum+p[1],0)/4;
 assert(Math.abs(meanLat-first.lat)<1e-9);
 assert(Math.abs(meanLon-first.lon)<1e-9);
 const a=corners[0],b=corners[1],dy=(b[0]-a[0])*111320,dx=(b[1]-a[1])*111320*Math.cos(first.lat*Math.PI/180);
 assert(Math.abs(Math.hypot(dx,dy)-25)<.4);
 assert(inVisibleCandidate25m(first,[{lat:first.lat,lon:first.lon,radiusM:100}]));
 assert(!inVisibleCandidate25m(first,[{lat:37.6,lon:127.06,radiusM:100}]));
 assert.notEqual(grid25mRsrpColor(-115),grid25mRsrpColor(-88));
 assert.equal(grid25mRsrpColor(0),'#ff0000');
 assert.equal(grid25mRsrpColor(-111),'#000000');
 assert.equal(grid25mRsrpColor(null),'#888888');
 assert.equal(MDT_RSRP_LEGEND.length,8);
});
test('frequency options select per-grid measured LTE EARFCN, Top1 uses measurement count',()=>{
 const expected=selectMdtGridMetric(first,'top1');
 assert.deepEqual(expected,{frequency:'1.8광',rsrp:-90.46,samples:8113});
 assert.deepEqual(selectMdtGridMetric(first,'900'),{frequency:'900',rsrp:-87.1,samples:527});
 assert.deepEqual(selectMdtGridMetric(first,'1.8협'),{frequency:'1.8협',rsrp:-93.43,samples:1107});
 assert.deepEqual(selectMdtGridMetric(first,'1.8광'),{frequency:'1.8광',rsrp:-90.46,samples:8113});
 assert.deepEqual(selectMdtGridMetric(first,'2.1'),{frequency:'2.1',rsrp:-95.92,samples:297});
 assert.equal(selectMdtGridMetric(first,'hidden'),null);
 const missing=grid.records.find(c=>!c.bands['2.1']);
 assert(missing,'some grids have no 2.1 observations');
 assert.equal(selectMdtGridMetric(missing,'2.1'),null);
 assert.equal(grid25mRsrpColor(-110),'#000051');
 assert.deepEqual(selectMdtGridMetric({bands:{'900':[-90,10],'1.8협':[-91,10]}},'top1'),{frequency:'900',rsrp:-90,samples:10});
});
test('overlay switch is placed before the entire-period selection, never changes clustering',()=>{
 const panel=fs.readFileSync(path.join(root,'components/analyst/quality-improvement-candidate-panel.tsx'),'utf8');
 const map=fs.readFileSync(path.join(root,'components/analyst/improvement-candidate-map.tsx'),'utf8');
 const two=fs.readFileSync(path.join(root,'components/analyst/quality-two-candidate-workspace.tsx'),'utf8');
 const alt=fs.readFileSync(path.join(root,'components/analyst/quality-model-alternative-workspace.tsx'),'utf8');
 const toggle=panel.indexOf('aria-label="25m MDT 격자 주파수 선택"');
 const period=panel.indexOf('aria-label="전체 기간 후보 분석 (기본)"');
 assert(toggle>=0&&period>toggle);
 assert(panel.includes('setMdtGridMode(event.target.value as MdtGridMode)'));
 assert.deepEqual(MDT_GRID_MODES.map(x=>x.value),['top1','900','1.8협','1.8광','2.1','hidden']);
 assert(map.includes("pane.style.zIndex='340'"));
 assert(map.includes('inVisibleCandidate25m(cell,areas)'));
 assert(map.includes('metric?0.34:0.17'));
 assert(map.includes('selectMdtGridMetric(cell,mdtGridMode)'));
 assert(map.includes('MDT_RSRP_LEGEND.map(item=>'));
 assert(map.includes('수집된 값 없음'));
 assert(map.includes("' · PotID '+cell.pot"),'tooltip displays original POT_GPOT ID immediately after measurement count');
 assert(two.includes('mdtGridMode={mdtGridMode}'));
 assert(alt.includes('mdtGridMode={mdtGridMode}'));
 assert(!fs.readFileSync(path.join(root,'scripts/build-quality-mixed-candidates.py'),'utf8').includes('mdt-grid-25m-v1.json'));
});
